class HTMLReporter:
    """Renders a ScanResult to a standalone HTML document."""

    def render(self, result: ScanResult) -> str:
        counts = result.counts()
        summary = [(s, counts[s]) for s in ("critical", "high", "medium", "low", "info")]
        return _TEMPLATE.render(
            brand=BRAND,
            tool=TOOL_NAME,
            tagline=TAGLINE,
            target=result.target,
            generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
            duration=result.duration,
            modules=", ".join(result.modules_run) or "none",
            summary=summary,
            findings=[f.to_dict() for f in result.sorted_findings()],
        )

    def write(self, result: ScanResult, path: str) -> None:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(self.render(result))
